'use strict'
/** RevisionPanel 浏览器结构契约，先锁现有 Vue 行为，原生化后逐条复跑。 */
const fs = require('fs'); const path = require('path'); const { chromium } = require('playwright-core')
const BASE = process.argv[2] || 'http://localhost:8080/lark-doc'; const results = []
function chromePath() { const root = path.join(process.env.HOME, 'Library/Caches/ms-playwright'); if (!fs.existsSync(root)) return null; for (const d of fs.readdirSync(root).filter(x => /^chromium-\d+$/.test(x)).sort().reverse()) { const p = path.join(root, d, 'chrome-mac-x64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'); if (fs.existsSync(p)) return p } return null }
function rec(name, ok, detail = '') { results.push(!!ok); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ` — ${detail}` : ''}`) }
async function main() {
  const browser = await chromium.launch({ headless: true, executablePath: chromePath() }); const page = await browser.newPage({ viewport: { width: 1700, height: 1000 } }); const errors = []; page.on('pageerror', e => errors.push(String(e)))
  page.setDefaultTimeout(10000)
  try {
    await page.goto(BASE, { waitUntil: 'networkidle', timeout: 60000 }); await page.waitForFunction(() => window.__larkDoc?.getEditor?.(), { timeout: 30000 })
    await page.evaluate(() => { window.__larkDoc.getEditor().commands.setContent({ type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: '前置' }] }, { type: 'paragraph', content: [{ type: 'text', text: '修订文本', marks: [{ type: 'revision', attrs: { revisionId: 'r1', author: 'local-user', kind: 'insert' } }] }] }, { type: 'paragraph', content: [{ type: 'text', text: '后置' }] }] }) })
    await page.waitForTimeout(120)
    const editor = page.locator('.ProseMirror'); await editor.click(); await page.waitForTimeout(100)
    const layer = page.locator('.lark-doc-revision-layer'); const panel = page.locator('.lark-doc-revision-panel')
    rec('修订层与面板进入 DOM', await layer.count() === 1 && await panel.count() >= 1)
    rec('面板声明 dialog/aria-label/fixed/270px', await panel.first().getAttribute('role') === 'dialog' && await panel.first().getAttribute('aria-label') === '修订建议' && await panel.first().evaluate(n => getComputedStyle(n).position === 'fixed' && getComputedStyle(n).width === '270px'))
    rec('头部、回复卡、六控件结构顺序', await panel.first().evaluate(n => { const kids = [...n.children]; return kids[0]?.classList.contains('lark-doc-revision-head') && kids[1]?.classList.contains('lark-doc-revision-reply') && kids[0].querySelectorAll('.lark-doc-revision-cell').length === 6 }))
    rec('控件包含分割条、拒绝在接受之前', await panel.first().evaluate(n => { const cells = [...n.querySelectorAll('.lark-doc-revision-cell')]; const buttons = [...n.querySelectorAll('.lark-doc-revision-btn')]; return cells.some(x => x.querySelector('.lark-doc-revision-split')) && buttons.some(x => x.classList.contains('is-reject')) && buttons.some(x => x.classList.contains('is-accept')) && buttons.findIndex(x => x.classList.contains('is-reject')) < buttons.findIndex(x => x.classList.contains('is-accept')) }))
    rec('回复卡含头像/作者/摘要', await panel.first().locator('.lark-doc-revision-avatar').count() === 1 && await panel.first().locator('.lark-doc-revision-author').count() === 1 && await panel.first().locator('.lark-doc-revision-body').count() === 1)
    rec('按钮全部无 title 且为 button', await panel.first().locator('.lark-doc-revision-btn').evaluateAll(ns => ns.every(n => n.tagName === 'BUTTON' && !n.hasAttribute('title') && n.getAttribute('aria-label') !== null)))
    // Separate fixture exposes the default public mode UI, even if the demo host hides its header.
    await page.evaluate(() => {
      const Facade = window.__larkDoc.document?.constructor || window.__larkDoc.constructor
      window.__larkDoc.destroy()
      const element = document.createElement('div')
      element.id = 'revision-lifecycle-acceptance'
      document.body.appendChild(element)
      window.__revisionContractDoc = new Facade({ element, storage: 'none', content: '<p>leftAAA</p><p>BBBend</p>', config: { modes: { persist: false, visible: true } } })
    })
    const fixture = page.locator('#revision-lifecycle-acceptance')
    await fixture.locator('.lark-doc-mode-select').hover()
    await fixture.locator('.lark-doc-select-menu [role="option"]').filter({ hasText: '修订' }).click()
    await page.waitForFunction(() => window.__revisionContractDoc.getEditor().storage.larkDocRevisionTracker.active)
    rec('通过真实模式菜单进入修订', await fixture.locator('.lark-doc-mode-select').innerText().then(text => text.includes('修订')))
    const bodyText = () => page.evaluate(() => window.__revisionContractDoc.getEditor().state.doc.textContent)
    const paragraphCount = () => fixture.locator('.ProseMirror > p').count()
    const selection = () => page.evaluate(() => { const { from, to } = window.__revisionContractDoc.getEditor().state.selection; return { from, to } })
    const setFixture = async html => page.evaluate(content => window.__revisionContractDoc.setContent(content), html)
    const selectCrossParagraph = async () => {
      await fixture.locator('.ProseMirror > p').first().scrollIntoViewIfNeeded()
      const points = await fixture.locator('.ProseMirror').evaluate(node => {
        const point = (paragraph, offset) => {
          const range = document.createRange()
          range.setStart(paragraph.firstChild, offset)
          range.collapse(true)
          const rect = range.getBoundingClientRect()
          return { x: rect.left, y: rect.top + rect.height / 2 }
        }
        return { start: point(node.children[0], 4), end: point(node.children[1], 3) }
      })
      await page.mouse.move(points.start.x, points.start.y)
      await page.mouse.down()
      await page.mouse.move(points.end.x, points.end.y, { steps: 12 })
      await page.mouse.up()
      await page.waitForFunction(() => { const selection = window.__revisionContractDoc.getEditor().state.selection; return selection.from === 5 && selection.to === 13 }, null, { timeout: 1500 })
      const range = await selection()
      if (range.from !== 5 || range.to !== 13) {
        const focus = await page.evaluate(() => ({ active: document.activeElement?.outerHTML.slice(0,350), editable: window.__revisionContractDoc.getEditor().isEditable, content: window.__revisionContractDoc.getEditor().getJSON(), domSelection: window.getSelection()?.toString() }))
        throw new Error(`Unexpected human selection: ${JSON.stringify({range,focus})}`)
      }
    }
    const proposal = fixture.locator('.lark-doc-revision-panel')
    await selectCrossParagraph()
    await page.keyboard.press('Backspace')
    await proposal.waitFor({ state: 'visible' })
    rec('跨段删除保留两段原文，只生成一条删除建议', await bodyText() === 'leftAAABBBend' && await paragraphCount() === 2 && await proposal.count() === 1 && (await proposal.innerText()).includes('删除：'))
    const boundary = fixture.locator('[data-type="revision-boundary"]')
    const marker = await boundary.evaluate(node => { const inner = node.firstElementChild; const style = getComputedStyle(inner, '::after'); return { text: node.textContent, width: node.getBoundingClientRect().width, afterWidth: style.width, content: style.content } })
    rec('段落边界为零宽字符与4.5px底线标记', marker.text === '\u200b' && marker.width === 0 && marker.afterWidth === '4.5px', JSON.stringify(marker))
    await proposal.locator('.is-reject').click()
    rec('拒绝跨段删除保留原文和段落，去掉所有建议', await bodyText() === 'leftAAABBBend' && await paragraphCount() === 2 && await proposal.count() === 0 && await boundary.count() === 0)
    await page.keyboard.press('Meta+z')
    await proposal.waitFor({ state: 'visible' })
    rec('撤销拒绝恢复同一删除建议', await boundary.count() === 1 && await bodyText() === 'leftAAABBBend')
    await proposal.locator('.is-accept').click()
    rec('接受跨段删除只移除选区并合并剩余原文', await bodyText() === 'leftend' && await paragraphCount() === 1 && await proposal.count() === 0)
    await page.keyboard.press('Meta+z')
    await proposal.waitFor({ state: 'visible' })
    rec('撤销接受恢复两段原文和建议', await bodyText() === 'leftAAABBBend' && await paragraphCount() === 2 && await boundary.count() === 1)
    await page.keyboard.press('Meta+Shift+z')
    rec('重做接受仍为一段且无多余新增建议', await bodyText() === 'leftend' && await paragraphCount() === 1 && await proposal.count() === 0)
    await setFixture('<p>left</p><p>right</p>')
    const startOfSecond = await fixture.locator('.ProseMirror > p').nth(1).evaluate(node => {
      const range = document.createRange()
      range.setStart(node.firstChild, 0)
      range.collapse(true)
      const rect = range.getBoundingClientRect()
      return { x: rect.left, y: rect.top + rect.height / 2 }
    })
    await page.mouse.click(startOfSecond.x, startOfSecond.y)
    await page.waitForFunction(() => window.__revisionContractDoc.getEditor().state.selection.from === 7, null, { timeout: 1500 })
    if ((await selection()).from !== 7) throw new Error('Paragraph-start caret was not reached')
    await page.keyboard.press('Backspace')
    await proposal.waitFor({ state: 'visible' })
    rec('段首退格只建议删除段落边界', await bodyText() === 'leftright' && await paragraphCount() === 2 && await boundary.count() === 1 && (await proposal.innerText()).includes('段落'))
    const savedHtml = await page.evaluate(() => window.__revisionContractDoc.getHTML())
    await setFixture(savedHtml)
    rec('HTML重载保留边界建议与身份', await boundary.count() === 1 && await proposal.count() === 1 && await paragraphCount() === 2)
    const evidenceDir = process.env.LARK_DOC_EVIDENCE_DIR
    if (evidenceDir) await page.screenshot({ path: path.join(evidenceDir, 'master-parity-local-revision-boundary.png'), fullPage: true })
    await proposal.locator('.is-accept').click()
    rec('接受边界建议合并两段并保留全部文字', await bodyText() === 'leftright' && await paragraphCount() === 1 && await boundary.count() === 0)
    await page.keyboard.press('Meta+z')
    await proposal.waitFor({ state: 'visible' })
    await proposal.locator('.is-reject').click()
    rec('拒绝边界建议保留两段并清除标记', await bodyText() === 'leftright' && await paragraphCount() === 2 && await boundary.count() === 0 && await proposal.count() === 0)
    const dragText = async (from, fromOffset, to, toOffset) => {
      const point = (node, offset) => {
        const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT)
        let text = walker.nextNode()
        while (text && offset > text.textContent.length) { offset -= text.textContent.length; text = walker.nextNode() }
        if (!text) throw new Error('Text coordinate is outside the rendered content')
        const range = document.createRange()
        range.setStart(text, offset)
        range.collapse(true)
        const rect = range.getBoundingClientRect()
        return { x: rect.left, y: rect.top + rect.height / 2 }
      }
      await from.scrollIntoViewIfNeeded()
      const start = await from.evaluate(point, fromOffset)
      const end = await to.evaluate(point, toOffset)
      await page.mouse.move(start.x, start.y)
      await page.mouse.down()
      await page.mouse.move(end.x, end.y, { steps: 12 })
      await page.mouse.up()
    }
    await setFixture('<pre><code>abc</code></pre><p>def</p>')
    const codeInput = fixture.locator('.lark-doc-code-input')
    const paragraph = fixture.locator('.ProseMirror > p').first()
    rec('修订态只锁定代码标题，代码正文仍可编辑', await fixture.locator('.lark-doc-code-caption').isDisabled() && await page.evaluate(() => window.__revisionContractDoc.getEditor().isEditable))
    await dragText(codeInput, 1, paragraph, 1)
    await page.waitForFunction(() => { const s = window.__revisionContractDoc.getEditor().state.selection; return s.from === 2 && s.to === 4 })
    await page.keyboard.press('Backspace')
    await proposal.waitFor({ state: 'visible' })
    rec('从代码向正文拖选停在代码区，仅产生代码尾部删除建议', await bodyText() === 'abcdef' && await fixture.locator('.lark-doc-code').count() === 1 && await paragraph.innerText() === 'def' && (await proposal.innerText()).includes('bc'))
    await proposal.locator('.is-accept').click()
    rec('接受代码内删除保留代码块与相邻正文', await codeInput.innerText() === 'a' && await paragraph.innerText() === 'def')
    await page.keyboard.press('Meta+z')
    await proposal.waitFor({ state: 'visible' })
    await proposal.locator('.is-reject').click()
    rec('撤销后拒绝代码删除恢复完整代码', await codeInput.innerText() === 'abc' && await paragraph.innerText() === 'def')
    await setFixture('<pre><code>abc</code></pre><p>def</p>')
    const paragraphId = await paragraph.getAttribute('data-block-id')
    await dragText(paragraph, 1, codeInput, 1)
    await page.waitForFunction(() => { const s = window.__revisionContractDoc.getEditor().state.selection; return s.from === 1 && s.to === 7 })
    await page.keyboard.press('Backspace')
    await proposal.waitFor({ state: 'visible' })
    rec('从正文拖入代码会将整个代码块纳入同一建议', await fixture.locator('.lark-doc-code.is-revision-delete').count() === 1 && await proposal.count() === 1 && await bodyText() === 'abcdef')
    await proposal.locator('.is-accept').click()
    rec('接受跨代码建议删除整块并保留正文块身份与剩余文字', await fixture.locator('.lark-doc-code').count() === 0 && await paragraph.innerText() === 'ef' && await paragraph.getAttribute('data-block-id') === paragraphId)
    await page.keyboard.press('Meta+z')
    await proposal.waitFor({ state: 'visible' })
    await proposal.locator('.is-reject').click()
    rec('撤销后拒绝跨代码建议恢复原两块且无额外空段', await fixture.locator('.lark-doc-code').count() === 1 && await paragraphCount() === 1 && await codeInput.innerText() === 'abc' && await paragraph.innerText() === 'def' && await proposal.count() === 0)
    await setFixture('<pre><code>abc</code></pre><p>def</p>')
    await dragText(paragraph, 1, codeInput, 1)
    await page.waitForFunction(() => window.__revisionContractDoc.getEditor().state.selection.to === 7)
    await page.keyboard.press('Backspace')
    await proposal.waitFor({ state: 'visible' })
    // These are separate selection gestures. PM treats nearby presses within
    // 500ms as a double click and selects the whole word instead of our range.
    await page.waitForTimeout(550)
    await dragText(paragraph, 2, codeInput, 1)
    await page.waitForFunction(() => window.__revisionContractDoc.getEditor().state.selection.to === 8, null, { timeout: 2000 }).catch(async error => {
      console.log('EXTEND_SELECTION', await page.evaluate(() => ({ selection: (() => { const s = window.__revisionContractDoc.getEditor().state.selection; return { from: s.from, to: s.to, anchor: s.anchor, head: s.head } })(), domText: getSelection()?.toString(), html: document.querySelector('#revision-lifecycle-acceptance .ProseMirror')?.innerHTML.slice(-2000) })))
      if (process.env.LARK_DOC_EVIDENCE_DIR) await page.screenshot({ path: path.join(process.env.LARK_DOC_EVIDENCE_DIR, 'master-parity-revision-extend-failure.png'), fullPage: true })
      throw error
    })
    await page.keyboard.press('Backspace')
    rec('扩展已有跨代码选区会将相邻未标记字符加入建议', (await proposal.innerText()).includes('de') && await bodyText() === 'abcdef')
    await proposal.locator('.is-accept').click()
    rec('接受扩展建议删除整代码和新纳入的字符', await fixture.locator('.lark-doc-code').count() === 0 && await paragraph.innerText() === 'f')
    await setFixture('<pre><code>abc</code></pre><p>def</p>')
    await fixture.locator('.lark-doc-mode-select').hover()
    await fixture.locator('.lark-doc-select-menu [role="option"]').filter({ has: page.locator('.lark-doc-select-item-label').filter({ hasText: /^编辑$/ }) }).click()
    rec('切回编辑态原代码标题重新可编辑', await fixture.locator('.lark-doc-code-caption').isEnabled())
    await page.evaluate(() => { window.__revisionContractDoc.destroy(); document.getElementById('revision-lifecycle-acceptance').remove(); delete window.__revisionContractDoc })
    rec('无页面脚本错误', errors.length === 0, errors.join(' | '))
  } finally { await browser.close() }
  if (results.some(x => !x)) process.exitCode = 1; console.log(`\n${results.filter(Boolean).length}/${results.length} 项通过`)
}
main().catch(e => { console.error('验证脚本异常:', e); process.exitCode = 1 })
