'use strict'

const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { chromium } = require('playwright-core')
const baseUrl = process.argv[2] || 'http://127.0.0.1:58742/lark-doc?verify=1'
const evidenceDir = process.env.LARK_DOC_EVIDENCE_DIR || '/tmp/lark-doc-v12e'
const results = []

async function main() {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1680, height: 1050 } })
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const check = (name, passed, detail) => { results.push({ name, passed, detail }); console.log(`${passed ? 'PASS' : 'FAIL'} ${name}`); assert(passed, name) }
  const atom = () => page.locator('.tiptap [data-type="inline-math"],.tiptap [data-type="block-math"]')
  const panel = () => page.getByRole('dialog', { name: '编辑公式', exact: true })
  const input = () => panel().getByRole('textbox', { name: 'LaTeX 公式', exact: true })
  const json = () => page.evaluate(() => window.__mathDoc.getJSON())
  const mathNodes = () => page.evaluate(() => { const nodes = []; window.__mathDoc.getEditor().state.doc.descendants(node => { if (node.type.name === 'inlineMath' || node.type.name === 'blockMath') nodes.push({ type: node.type.name, ...node.attrs }) }); return nodes })
  const click = async locator => {
    await locator.scrollIntoViewIfNeeded()
    const r = await locator.boundingBox(), viewport = page.viewportSize()
    assert(r && r.x + r.width / 2 >= 0 && r.x + r.width / 2 <= viewport.width && r.y + r.height / 2 >= 0 && r.y + r.height / 2 <= viewport.height, 'Visible mouse target required')
    await page.mouse.click(r.x + r.width / 2, r.y + r.height / 2)
  }
  const type = async value => { await click(input()); await page.keyboard.press('Meta+a'); await page.keyboard.press('Backspace'); if (value) await page.keyboard.type(value) }
  const setup = async content => page.evaluate(content => {
    const Facade = window.__larkDoc.document?.constructor || window.__larkDoc.constructor
    window.__larkDoc.destroy()
    const element = document.createElement('div')
    document.body.appendChild(element)
    window.__mathDoc = new Facade({ element, storage: 'none', content })
  }, content)
  try {
    await page.goto(baseUrl, { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => window.__larkDoc?.getEditor?.())
    await setup('<p></p>')
    await click(page.locator('.tiptap p').first())
    await page.keyboard.type('/')
    check('Source single formula entry replaces the former duplicate block entry', await page.locator('[data-command-id="inlineMath"] .lark-doc-command-label').innerText() === '公式' && await page.locator('[data-command-id="blockMath"]').count() === 0)
    await click(page.locator('[data-command-id="inlineMath"]'))
    await panel().waitFor()
    await page.waitForTimeout(80)
    const geometry = await panel().evaluate(e => ({ rect: e.getBoundingClientRect().toJSON(), input: e.querySelector('textarea').getBoundingClientRect().toJSON(), fontSize: getComputedStyle(e.querySelector('textarea')).fontSize, lineHeight: getComputedStyle(e.querySelector('textarea')).lineHeight, focused: document.activeElement === e.querySelector('textarea') }))
    check('Slash inserts an inline atom and opens the measured 400×98 anchored editor', geometry.rect.width === 400 && geometry.rect.height === 98 && geometry.input.width === 366 && geometry.input.height === 40 && geometry.fontSize === '14px' && geometry.lineHeight === '22px' && geometry.focused && (await mathNodes())[0].type === 'inlineMath', geometry)
    check('Formula editor uses a nonmodal surface without backdrop or submit button', await panel().getAttribute('aria-modal') === null && await page.locator('.lark-doc-dialog-backdrop').count() === 0 && await panel().getByRole('button', { name: '插入', exact: true }).count() === 0)
    await type('x^2+1')
    await atom().locator('.katex').waitFor()
    check('Typing updates raw LaTeX and live KaTeX preview', (await mathNodes())[0].latex === 'x^2+1')
    await page.keyboard.press('Escape')
    check('Escape finishes and saves the expression', await panel().count() === 0 && (await mathNodes())[0].latex === 'x^2+1')
    await click(atom())
    check('Click reopens exact editable source', await input().inputValue() === 'x^2+1')
    await page.keyboard.press('End')
    await page.keyboard.type('+3')
    await page.keyboard.press('Escape')
    check('Re-entry edits update the same atom', (await mathNodes()).length === 1 && (await mathNodes())[0].latex === 'x^2+1+3')
    await page.keyboard.press('Meta+z')
    check('One undo restores the previous complete expression', (await mathNodes())[0].latex === 'x^2+1')
    await page.keyboard.press('Meta+Shift+z')
    check('Redo restores the edited expression', (await mathNodes())[0].latex === 'x^2+1+3')
    await click(atom())
    await type('\\badcommand{')
    await atom().filter({ hasText: '无效公式' }).waitFor()
    check('Invalid expressions show the source warning while retaining the exact input', (await mathNodes())[0].latex === '\\badcommand{' && await panel().count() === 1)
    await page.keyboard.press('Escape')
    await click(atom())
    check('Invalid expressions stay editable after finishing', await input().inputValue() === '\\badcommand{')
    await type('x+2')
    await atom().locator('.katex').waitFor()
    await page.keyboard.press('Escape')
    check('Repairing invalid LaTeX restores the rendered formula', await atom().locator('.katex').count() === 1 && (await mathNodes())[0].latex === 'x+2')
    await click(atom())
    await type('')
    await page.keyboard.press('Escape')
    check('Empty formula remains as an editable source placeholder', await atom().innerText() === '添加 LaTeX 公式' && (await mathNodes())[0].latex === '')
    await click(atom())
    await type('x+1')
    await page.keyboard.press('Enter')
    await page.keyboard.type('+2')
    check('Enter adds an input line and keeps the editor open', await panel().count() === 1 && (await input().inputValue()).includes('\n') && (await panel().boundingBox()).height > 98)
    await click(page.locator('.lark-doc-paper'))
    check('Outside click finishes without dropping multiline source', await panel().count() === 0 && (await mathNodes())[0].latex === 'x+1\n+2')
    await click(atom())
    const newTab = page.waitForEvent('popup')
    await click(panel().getByRole('link', { name: /查看帮助文档/ }))
    const help = await newTab
    try {
      await help.waitForURL(url => url.href.includes('/articles/894598450617'), { waitUntil: 'commit' })
      check('Help opens the actual source documentation in a new tab', help.url().startsWith('https://www.feishu.cn/hc/'))
    } finally { await help.close() }
    await page.keyboard.press('Escape')
    check('Escape outside the raw input keeps the help-return editor open, matching source', await panel().count() === 1)
    await click(input())
    await page.keyboard.press('Escape')
    const saved = await json()
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => window.__larkDoc?.getEditor?.())
    await setup(saved)
    await click(atom())
    check('JSON reload preserves LaTeX and live editing', await input().inputValue() === 'x+1\n+2')
    await page.evaluate(() => window.__mathDoc.patchProps({ config: { features: { math: false } } }))
    check('Disabling math closes an active editor', await panel().count() === 0)
    await click(atom())
    check('Disabled math stays readable without reopening mutation controls', await panel().count() === 0 && (await mathNodes())[0].latex === 'x+1\n+2')
    await page.evaluate(() => { window.__mathDoc.patchProps({ config: { features: { math: true } } }); window.__mathDoc.setReadonly(true) })
    const readonly = await json()
    await click(atom())
    check('Read mode blocks formula edits and preserves exact document JSON', await panel().count() === 0 && JSON.stringify(await json()) === JSON.stringify(readonly))
    await page.evaluate(() => {
      window.__mathDoc.setReadonly(false)
      window.__mathDoc.setContent({ type: 'doc', content: [{ type: 'blockMath', attrs: { latex: 'a^2+b^2', blockId: 'legacy_math' } }] })
    })
    await click(atom())
    await type('a^2+b^2=c^2')
    await page.keyboard.press('Escape')
    check('Legacy block formulas retain their type and identity after editing', (await mathNodes())[0].type === 'blockMath' && (await mathNodes())[0].blockId === 'legacy_math' && (await mathNodes())[0].latex === 'a^2+b^2=c^2')
    await page.evaluate(() => window.__mathDoc.setContent(window.__mathDoc.getHTML()))
    check('HTML roundtrip retains legacy formula source', (await mathNodes())[0].latex === 'a^2+b^2=c^2')
    await click(atom())
    await page.screenshot({ path: path.join(evidenceDir, 'master-parity-local-math-editor.png') })
    check('No uncaught page errors', errors.length === 0, errors)
  } catch (error) {
    console.error('DOCUMENT', JSON.stringify(await json().catch(() => null)))
    await page.screenshot({ path: path.join(evidenceDir, 'master-parity-local-math-failure.png') })
    throw error
  } finally {
    fs.writeFileSync(path.join(evidenceDir, 'master-parity-local-math.json'), JSON.stringify({ url: baseUrl, results, errors }, null, 2))
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
