'use strict'
const assert = require('assert')
const { chromium } = require('playwright-core')
const BASE = process.argv[2] || 'http://127.0.0.1:58742/lark-doc?verify=1'
const results = []
async function main() {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1700, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const check = (name, passed) => { results.push(passed); console.log(`${passed ? 'PASS' : 'FAIL'} ${name}`); assert(passed, name) }
  const panel = page.getByRole('dialog', { name: '按钮配置', exact: true })
  const json = () => page.evaluate(() => window.__larkDoc.getJSON())
  const open = async () => {
    await page.evaluate(() => window.__larkDoc.setContent('<p></p>'))
    await page.locator('.ProseMirror p').first().click()
    await page.keyboard.type('/打开超链接')
    await page.locator('[data-command-id="open_link"]').click()
    await panel.waitFor()
  }
  try {
    await page.goto(BASE, { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => window.__larkDoc?.getEditor?.())
    await open()
    check('Panel has the expected dialog label and 20-character text input', await panel.getByRole('textbox', { name: '按钮文字' }).getAttribute('maxlength') === '20')
    check('Color palette retains 16 choices', await panel.locator('.lark-doc-isv-color-item').count() === 16)
    const text = panel.getByRole('textbox', { name: '按钮文字' })
    await text.selectText()
    await page.keyboard.type('连续输入ABC')
    check('Real sequential keyboard input retains text and focus', await text.inputValue() === '连续输入ABC' && await text.evaluate(element => document.activeElement === element))
    await panel.getByRole('button', { name: '确定', exact: true }).focus()
    await page.keyboard.press('Enter')
    check('Keyboard submit of an empty URL keeps the panel and shows validation', await panel.count() === 1 && await panel.locator('.lark-doc-isv-field-explain').innerText() === '超链接不合法，请重新输入')
    const link = panel.getByRole('textbox', { name: '超链接地址' })
    await link.click()
    await page.keyboard.type('https://www.barenkeji.com')
    check('Sequential URL input does not lose characters or focus', await link.inputValue() === 'https://www.barenkeji.com' && await link.evaluate(element => document.activeElement === element))
    await page.keyboard.press('Enter')
    await panel.waitFor({ state: 'detached' })
    const saved = await json()
    check('Enter inserts exactly one button with the expected text and URL', saved.content.filter(node => node.type === 'isv').length === 1 && saved.content.find(node => node.type === 'isv').attrs.linkUrl === 'https://www.barenkeji.com' && saved.content.find(node => node.type === 'isv').attrs.buttonText === '连续输入ABC')
    const button = page.locator('.docx-button-component')
    await button.focus()
    const popupEvent = page.waitForEvent('popup')
    await page.keyboard.press('Enter')
    const popup = await popupEvent
    check('Keyboard activation opens the real barenkeji URL in a separate page', /^https:\/\/www\.barenkeji\.com\/?/.test(popup.url()))
    await popup.close()
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => window.__larkDoc?.getEditor?.())
    await page.evaluate(saved => window.__larkDoc.setContent(saved), saved)
    check('Button reload retains stable instance and action attributes', JSON.stringify(await json()) === JSON.stringify(saved))
    await open()
    const select = panel.getByRole('button', { name: '执行操作', exact: true })
    await select.focus()
    await page.keyboard.press('ArrowDown')
    await panel.getByRole('listbox').waitFor()
    check('Keyboard opens the three-action dropdown', await panel.getByRole('option').count() === 3)
    await panel.getByRole('option').first().focus()
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    check('Keyboard selects follow action and hides the URL row', await panel.getByRole('textbox', { name: '超链接地址' }).count() === 0 && await select.innerText() === '关注文档更新')
    await page.keyboard.press('Escape')
    check('Escape cancels without inserting a button', await panel.count() === 0 && !(await json()).content.some(node => node.type === 'isv'))
    await open()
    await panel.getByRole('button', { name: '取消', exact: true }).focus()
    await page.keyboard.press('Space')
    check('Space activates Cancel without writing a block', await panel.count() === 0 && !(await json()).content.some(node => node.type === 'isv'))
    await open()
    const beforeReadonly = await json()
    await page.evaluate(() => window.__larkDoc.patchProps({ readonly: true }))
    check('Readonly revocation immediately removes the active configuration panel', await panel.count() === 0 && JSON.stringify(await json()) === JSON.stringify(beforeReadonly))
    await page.evaluate(() => window.__larkDoc.patchProps({ readonly: false }))
    await open()
    await page.evaluate(() => window.__larkDoc.patchProps({ config: { features: { insert: false } } }))
    check('Live insertion disable immediately closes the configuration panel', await panel.count() === 0)
    await page.evaluate(() => window.__larkDoc.patchProps({ config: { features: { insert: true } } }))
    check('No browser script errors', errors.length === 0)
  } finally { await browser.close() }
  console.log(`RESULT ${results.filter(Boolean).length}/${results.length}`)
}
main().catch(error => { console.error(error); process.exitCode = 1 })
