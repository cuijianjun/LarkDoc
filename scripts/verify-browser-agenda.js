'use strict'
const assert = require('assert')
const { chromium } = require('playwright-core')
const BASE = process.argv[2] || 'http://127.0.0.1:58742/lark-doc?verify=1'
const results = []
async function main() {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1680, height: 1050 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const check = (name, passed) => { console.log(`${passed ? 'PASS' : 'FAIL'} ${name}`); results.push(passed); assert(passed, name) }
  const json = () => page.evaluate(() => window.__larkDoc.getJSON())
  const item = index => page.locator('.ProseMirror [data-type="agenda-item"]').nth(index)
  const undo = () => page.keyboard.press('Meta+z')
  try {
    await page.goto(BASE, { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => window.__larkDoc?.getEditor?.())
    await page.evaluate(() => window.__larkDoc.setContent('<p></p>'))
    await page.locator('.ProseMirror p').first().click()
    await page.keyboard.type('/会议议程')
    const command = page.locator('[data-command-id="agenda"]')
    check('Slash agenda is enabled', await command.getAttribute('aria-disabled') !== 'true' && !await command.isDisabled())
    await command.click()
    await item(1).waitFor()
    check('One slash action inserts two items with 20/10 minutes', await page.locator('[data-type="agenda-item"]').count() === 2 && await item(0).locator('input').inputValue() === '20' && await item(1).locator('input').inputValue() === '10')
    check('Insertion leaves an editable paragraph after the agenda', await page.evaluate(() => window.__larkDoc.getEditor().state.selection.$from.parent.type.name === 'paragraph'))
    const initial = await json()
    await undo()
    check('Single keyboard undo removes both agenda items', await page.locator('[data-type="agenda"]').count() === 0)
    await page.keyboard.press('Meta+Shift+z')
    check('Redo retains item identities', JSON.stringify(await json()) === JSON.stringify(initial))
    const title = item(0).locator('[data-type="agenda-title"]')
    await title.click()
    await page.keyboard.type('会议讨论目标')
    await page.keyboard.press('Enter')
    await page.keyboard.type('讨论正文')
    check('Title Enter moves into the real editable body', await title.innerText() === '会议讨论目标' && await item(0).locator('[data-type="agenda-content"]').innerText() === '讨论正文')
    const duration = item(0).getByRole('spinbutton', { name: '议程时长（分钟）' })
    await duration.click()
    await page.keyboard.press('ArrowUp')
    await page.keyboard.press('Enter')
    check('Native duration step increments only the selected item', await duration.inputValue() === '21' && await item(1).locator('input').inputValue() === '10')
    await undo()
    check('Duration has its own undo step preserving rich text', await duration.inputValue() === '20' && await title.innerText() === '会议讨论目标')
    await duration.fill('0')
    await page.keyboard.press('Enter')
    check('Invalid duration restores the persisted value', await duration.inputValue() === '20')
    await duration.fill('99')
    await page.keyboard.press('Escape')
    check('Escape cancels an uncommitted duration', await duration.inputValue() === '20')
    const saved = await json()
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => window.__larkDoc?.getEditor?.())
    await page.evaluate(saved => window.__larkDoc.setContent(saved), saved)
    check('Browser reload retains title, body, duration and stable IDs', JSON.stringify(await json()) === JSON.stringify(saved))
    const html = await page.evaluate(() => window.__larkDoc.getHTML())
    await page.evaluate(html => window.__larkDoc.setContent(html), html)
    check('Sanitized public HTML import retains exact agenda data', JSON.stringify(await json()) === JSON.stringify(saved))
    await page.evaluate(() => window.__larkDoc.patchProps({ readonly: true }))
    check('Readonly keeps readable text and immediately hides editing controls', await item(0).getAttribute('data-agenda-editable') === 'false' && !await item(0).locator('input').isVisible() && await title.innerText() === '会议讨论目标')
    check('Readonly API actions cannot mutate agenda data', await page.evaluate(() => { const editor = window.__larkDoc.getEditor(); return !editor.commands.insertAgenda() && !editor.commands.removeAgendaItem(1) && !editor.commands.setAgendaDuration(1, 23) }))
    await page.evaluate(() => window.__larkDoc.patchProps({ readonly: false, config: { commands: { disabled: ['agenda'] } } }))
    check('Live command disable closes the agenda controls', await item(0).getAttribute('data-agenda-editable') === 'false')
    await page.evaluate(() => window.__larkDoc.patchProps({ config: { commands: { disabled: [] } } }))
    await item(0).hover()
    await item(0).getByRole('button', { name: '删除议程项' }).click()
    check('Delete removes exactly one item and leaves its sibling', await page.locator('[data-type="agenda-item"]').count() === 1 && await item(0).locator('input').inputValue() === '10')
    await undo()
    check('Undo restores the removed rich-text item and identity', JSON.stringify(await json()) === JSON.stringify(saved))
    const green = await item(0).evaluate(element => ({ border: getComputedStyle(element).borderLeftColor, brand: getComputedStyle(element.closest('.lark-doc')).getPropertyValue('--ld-brand-content') }))
    check('Agenda uses the original green theme', /rgb\(0, 169, 121\)|#00a979/i.test(green.border) || /#00a979/i.test(green.brand), green)
    await page.emulateMedia({ media: 'print' })
    check('Print retains durations while hiding editable controls', !await item(0).locator('input').isVisible() && await item(0).locator('.lark-doc-agenda-duration-label').isVisible())
    await page.emulateMedia({ media: 'screen' })
    check('No browser script errors', errors.length === 0)
  } finally { await browser.close() }
  console.log(`RESULT ${results.filter(Boolean).length}/${results.length}`)
}
main().catch(error => { console.error(error); process.exitCode = 1 })
